"""Score the phase 5 one-shot test against its pre-registered predictions (RESULTS.md, "Phase 5 design").

Reads runs/gemma3-4b-edit/{split}_{off,edited,placebo}.csv (weight_edit.py test) and the phase 4
retrieval runs for comparison; writes runs/gemma3-4b-edit/analysis.md.

  python analyze_phase5.py
"""

import os

import pandas as pd

from grader import grade

D = os.path.join("runs", "gemma3-4b-edit")
P4 = os.path.join("runs", "gemma3-4b-phase4")
SPLITS = ("train", "paraphrase", "holdout")


def load(d, split, arm):
    return pd.read_csv(os.path.join(d, f"{split}_{arm}.csv")).set_index("question")


def fixed_broke(off, on, subset=None):
    idx = off.index if subset is None else off.index.intersection(subset)
    o, n = off.loc[idx, "correct"], on.loc[idx, "correct"]
    return {"n": len(idx), "wrong_off": int((o == 0).sum()), "right_off": int((o == 1).sum()),
            "fixed": int(((o == 0) & (n == 1)).sum()), "broke": int(((o == 1) & (n == 0)).sum()),
            "acc_off": o.mean(), "acc_on": n.mean()}


def main():
    corr = pd.read_csv(os.path.join(P4, "corrections.csv"))
    edited_q = set(corr["question"])
    para = pd.read_csv("questions_trivia_v2_paraphrase.csv").set_index("question")
    para_src = set(para.index[para["source_question"].isin(edited_q)])
    lines = ["# Phase 5 test — analysis (generated by analyze_phase5.py)", ""]

    def out(s=""):
        print(s)
        lines.append(s)

    # Fixed / broke for every split and arm, against the unedited run of the same pipeline.
    out("| split | arm | acc off | acc on | fixed | broke |")
    out("|---|---|---|---|---|---|")
    res = {}
    for split in SPLITS:
        off = load(D, split, "off")
        for arm in ("edited", "placebo"):
            r = fixed_broke(off, load(D, split, arm))
            res[split, arm] = r
            out(f"| {split} | {arm} | {r['acc_off']:.1%} | {r['acc_on']:.1%} | {r['fixed']} / {r['wrong_off']} | "
                f"{r['broke']} / {r['right_off']} |")
    out()

    # 1. Training: the 119 corrected questions.
    off, ed = load(D, "train", "off"), load(D, "train", "edited")
    t = fixed_broke(off, ed, edited_q)
    out(f"**P1 (train fixes >= 60% of the 119):** {int(ed.loc[list(edited_q), 'correct'].sum())} / {len(edited_q)} "
        f"corrected questions right after the edit ({ed.loc[list(edited_q), 'correct'].mean():.1%}). "
        f"In this pipeline's unedited run {t['wrong_off']} of them are wrong; the edit fixes {t['fixed']} "
        f"({t['fixed'] / max(t['wrong_off'], 1):.1%}) and breaks {t['broke']}.")

    # 2. Paraphrases of edited questions that are wrong without memory.
    poff, ped = load(D, "paraphrase", "off"), load(D, "paraphrase", "edited")
    p = fixed_broke(poff, ped, para_src)
    rg = pd.read_csv(os.path.join(P4, "paraphrase_gated_pairs.csv")).set_index("question")
    rg = rg.loc[rg.index.intersection(para_src)]
    g_fix, g_wrong = int(((rg.correct_off == 0) & (rg.correct_on == 1)).sum()), int((rg.correct_off == 0).sum())
    out(f"**P2 (paraphrase fixes 25–60%, fewer than gated retrieval):** edit fixes {p['fixed']} / {p['wrong_off']} "
        f"({p['fixed'] / max(p['wrong_off'], 1):.1%}) of wrong-off paraphrases whose source was edited "
        f"(broke {p['broke']}). Gated retrieval on the same definition: {g_fix} / {g_wrong} "
        f"({g_fix / max(g_wrong, 1):.1%}).")

    # 3. Held-out collateral, edited vs placebo.
    he, hp = res["holdout", "edited"], res["holdout", "placebo"]
    out(f"**P3 (held-out: edit breaks >= 3, placebo within ± 5):** edited broke {he['broke']}, placebo broke "
        f"{hp['broke']} (difference {he['broke'] - hp['broke']:+d}). Fixed: {he['fixed']} vs {hp['fixed']}.")

    # 4. Does the placebo emit its shuffled target on the edited training questions?
    tg = pd.read_csv(os.path.join(D, "placebo_targets.csv")).set_index("question")
    pl = load(D, "train", "placebo")
    hits = [grade(q, str(pl.loc[q, "answer"]), str(tg.loc[q, "placebo_answer"]))[0] for q in tg.index]
    still = pl.loc[list(edited_q), "correct"].sum()
    out(f"**P4 (placebo emits the shuffled answer on >= 50%):** {sum(hits)} / {len(hits)} ({sum(hits) / len(hits):.1%}). "
        f"The placebo leaves {int(still)} of the 119 answered with the true answer.")

    # 5. Accuracy against gated retrieval (phase 4, int8 pipeline; each against its own baseline).
    out("**P5 (edit doesn't beat gated retrieval on any set):**")
    out()
    out("| set | edited acc (own off) | gated retrieval acc (own off) |")
    out("|---|---|---|")
    for split in SPLITS:
        g = pd.read_csv(os.path.join(P4, f"{split}_gated_pairs.csv"))
        r = res[split, "edited"]
        out(f"| {split} | {r['acc_on']:.1%} ({r['acc_off']:.1%}) | {g.correct_on.mean():.1%} ({g.correct_off.mean():.1%}) |")
    out()

    # Copy check: how many edited-train fixes are the canonical corrected answer verbatim.
    fixes = [q for q in edited_q if off.loc[q, "correct"] == 0 and ed.loc[q, "correct"] == 1]
    canon = dict(zip(corr["question"], corr["correct_answer"].astype(str)))
    verbatim = sum(grade(q, str(ed.loc[q, "answer"]), canon[q])[0] for q in fixes)
    out(f"Edited-train fixes that contain the canonical corrected answer: {verbatim} / {len(fixes)}.")
    with open(os.path.join(D, "analysis.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
