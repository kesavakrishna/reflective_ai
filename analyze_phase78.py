"""Score phases 7 and 8 against their pre-registered predictions (RESULTS.md, "Phase 7 design",
"Phase 8 design"). Writes runs/gemma3-4b-chain/analysis.md and runs/gemma3-4b-neardup/analysis.md.

  python analyze_phase78.py [7|8]      # default: both
"""

import os
import sys

import numpy as np
import pandas as pd

from agent import final_answer
from grader import grade

TWOHOP = os.path.join("runs", "gemma3-4b-twohop")
P7 = os.path.join("runs", "gemma3-4b-chain")
P8 = os.path.join("runs", "gemma3-4b-neardup")
P4 = os.path.join("runs", "gemma3-4b-phase4")


def load(path):
    return pd.read_csv(path).drop_duplicates("question").set_index("question")


def ids(x):
    return [int(i) for i in str(x).split(";") if i.strip() and i != "nan"]


def writer(path):
    lines = []

    def out(s=""):
        print(s)
        lines.append(s)

    def save():
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    return out, save


def entity_of(reply):
    """The text after "Entity:" up to the next line (chain replies)."""
    s = str(reply)
    i = s.find("Entity:")
    return s[i + 7:].split("\n")[0].strip() if i >= 0 else ""


def phase7():
    out, save = writer(os.path.join(P7, "analysis.md"))
    out("# Phase 7 — chain prompt on the two-hop set (generated by analyze_phase78.py)\n")
    items = pd.read_csv("questions_twohop.csv")
    items["direct"] = pd.read_csv("questions_twohop_direct.csv")["question"].values
    bridge = dict(zip(items["question"], items["bridge_aliases"]))
    d_off, t_off = load(os.path.join(TWOHOP, "direct_off.csv")), load(os.path.join(TWOHOP, "twohop_off.csv"))
    targets = [r.question for r in items.itertuples()
               if d_off.loc[r.direct, "correct"] == 1 and t_off.loc[r.question, "correct"] == 0]
    right_off = [q for q in items["question"] if t_off.loc[q, "correct"] == 1]
    runs = {c: load(os.path.join(TWOHOP, f"twohop_{c}.csv")) for c in ("gated", "oracle")}
    runs.update({c: load(os.path.join(P7, f"twohop_{c}.csv")) for c in ("off_chain", "gated_chain", "oracle_chain")})
    out(f"Targets (phase 6, original prompt): {len(targets)}; right with memory off: {len(right_off)}.\n")
    out("| arm | two-hop acc (114) | targets fixed | broke (of right-off) | still-wrong targets answering the bridge | "
        "entity line names the bridge (targets) | replies with an Answer: line |")
    out("|---|---|---|---|---|---|---|")
    res = {}
    for c, r in runs.items():
        chain = c.endswith("_chain")
        fin = {q: final_answer(str(r.loc[q, "answer"])) if chain else str(r.loc[q, "answer"]) for q in r.index}
        fixed = sum(r.loc[q, "correct"] for q in targets)
        broke = sum(1 - r.loc[q, "correct"] for q in right_off)
        wrong = [q for q in targets if r.loc[q, "correct"] == 0]
        copy = sum(grade(q, fin[q], bridge[q])[0] for q in wrong)
        ent = sum(grade(q, entity_of(r.loc[q, "answer"]), bridge[q])[0] for q in targets) if chain else None
        fmt = np.mean(["Answer:" in str(r.loc[q, "answer"]) for q in r.index]) if chain else None
        res[c] = {"fixed": fixed, "broke": broke, "copy": copy, "ent": ent}
        out(f"| {c} | {r['correct'].mean():.1%} | {fixed} / {len(targets)} ({fixed / len(targets):.1%}) | {broke} / {len(right_off)} | "
            f"{copy} / {len(wrong)} | {'—' if ent is None else f'{ent} / {len(targets)}'} | {'—' if fmt is None else f'{fmt:.0%}'} |")
    out()
    n = len(targets)
    out(f"**P1 (off_chain fixes <= 10%):** {res['off_chain']['fixed']} / {n} ({res['off_chain']['fixed'] / n:.1%}).")
    out(f"**P2 (oracle_chain fixes >= 55%):** {res['oracle_chain']['fixed']} / {n} ({res['oracle_chain']['fixed'] / n:.1%}); "
        f"oracle {res['oracle']['fixed']}.")
    out(f"**P3 (oracle_chain copies the bridge on <= 2 still-wrong targets):** {res['oracle_chain']['copy']} (oracle: {res['oracle']['copy']}).")
    out(f"**P4 (gated_chain within 2 of oracle_chain):** {res['gated_chain']['fixed']} vs {res['oracle_chain']['fixed']}.")
    out(f"**P5 (oracle_chain breaks <= oracle + 2 = {res['oracle']['broke'] + 2}):** {res['oracle_chain']['broke']}.")
    # Where do oracle_chain's remaining failures come from: wrong entity, or right entity but wrong hop?
    r = runs["oracle_chain"]
    wrong = [q for q in targets if r.loc[q, "correct"] == 0]
    right_ent = [q for q in wrong if grade(q, entity_of(r.loc[q, "answer"]), bridge[q])[0]]
    out(f"\noracle_chain still-wrong targets: {len(wrong)}; of those, the entity line names the bridge in {len(right_ent)} "
        f"(so the second hop is what fails).")
    for q in wrong[:12]:
        out(f"- {str(r.loc[q, 'answer'])[:110]!r}  (expected {t_off.loc[q, 'expected_answer'].split('|')[0]})")
    save()


def phase8():
    from llm_client import embed  # MiniLM, unit-norm; cos = dot

    out, save = writer(os.path.join(P8, "analysis.md"))
    out("# Phase 8 — near-duplicate gate stress test (generated by analyze_phase78.py)\n")
    items = pd.read_csv("questions_neardup.csv")
    corr = pd.read_csv(os.path.join(P4, "corrections.csv"))
    own_id = dict(zip(corr["question"], corr["id"]))
    r = {c: load(os.path.join(P8, f"neardup_{c}.csv")) for c in ("off", "corrections", "gated")}
    src = dict(zip(items["question"], items["source_aliases"]))
    n = len(items)

    def cos(a, b):
        u, v = np.asarray(embed(a)), np.asarray(embed(b))
        return float(u @ v / (np.linalg.norm(u) * np.linalg.norm(v)))

    sim_nd = [cos(x.question, x.source_question) for x in items.itertuples()]
    fired = [bool(ids(r["gated"].loc[x.question, "retrieved_correction_ids"])) for x in items.itertuples()]
    own_top1 = [ids(r["corrections"].loc[x.question, "retrieved_correction_ids"])[:1] == [own_id[x.source_question]]
                for x in items.itertuples()]
    both = sum(a and b for a, b in zip(fired, own_top1))
    out(f"Items: {n}. Cos to the source question: median {np.median(sim_nd):.3f}, min {min(sim_nd):.3f}, max {max(sim_nd):.3f}.\n")
    out(f"**P1 (own correction top-1 and gate fired on >= 50%):** {both} / {n} ({both / n:.1%}); gate fired at all: {sum(fired)}.")

    copy = {c: [grade(q, str(r[c].loc[q, "answer"]), src[q])[0] for q in items["question"]] for c in r}
    out(f"**P2 (copy harm >= 15% gated, <= 3% off):** gated {sum(copy['gated'])} / {n} ({np.mean(copy['gated']):.1%}), "
        f"off {sum(copy['off'])} / {n} ({np.mean(copy['off']):.1%}), ungated {sum(copy['corrections'])}.")
    out(f"**P3 (gated within 3 of ungated):** {sum(copy['gated'])} vs {sum(copy['corrections'])}.")
    right = [q for q in items["question"] if r["off"].loc[q, "correct"] == 1]
    broke = [q for q in right if r["gated"].loc[q, "correct"] == 0]
    out(f"**P4 (gated breaks >= 15% of right-off):** {len(broke)} / {len(right)} "
        f"({len(broke) / max(len(right), 1):.1%}); of those, answering the stored answer: "
        f"{sum(grade(q, str(r['gated'].loc[q, 'answer']), src[q])[0] for q in broke)}.")
    fired_copy = [c for c, f in zip(copy["gated"], fired) if f]
    out(f"Among items where the gate fired: copy harm {sum(fired_copy)} / {len(fired_copy)}.")

    # P5: can any threshold keep phase 4 paraphrases (should fire) and block near-duplicates?
    para = pd.read_csv("questions_trivia_v2_paraphrase.csv")
    para = para[para["source_question"].isin(own_id)]
    sim_pa = [cos(x.question, x.source_question) for x in para.itertuples()]
    best = None
    for t in np.arange(0.50, 1.0001, 0.005):
        keep = np.mean(np.array(sim_pa) >= t)
        block = np.mean(np.array(sim_nd) < t)
        if best is None or min(keep, block) > min(best[1], best[2]):
            best = (t, keep, block)
    ok = [t for t in np.arange(0.50, 1.0001, 0.005)
          if np.mean(np.array(sim_pa) >= t) >= 0.9 and np.mean(np.array(sim_nd) < t) >= 0.9]
    out(f"**P5 (no threshold keeps >= 90% of paraphrases and blocks >= 90% of near-duplicates):** "
        f"{'none exists' if not ok else f'thresholds that do: {ok[0]:.3f}-{ok[-1]:.3f}'}. "
        f"Best balance at {best[0]:.3f}: keeps {best[1]:.1%} of {len(sim_pa)} paraphrases, blocks {best[2]:.1%} of near-duplicates. "
        f"Paraphrase cos median {np.median(sim_pa):.3f}; near-duplicate {np.median(sim_nd):.3f}.")
    pd.DataFrame({"question": items["question"], "cos_source": sim_nd, "gate_fired": fired, "own_top1": own_top1,
                  "copy_off": copy["off"], "copy_gated": copy["gated"]}).to_csv(os.path.join(P8, "neardup_sims.csv"), index=False)
    out()
    for x in items.itertuples():
        if copy["gated"][list(items["question"]).index(x.question)]:
            out(f"- copied {x.source_answer!r}: {x.question[:110]}  (expected {x.expected_answer.split('|')[0]})")
    save()


if __name__ == "__main__":
    which = sys.argv[1:] or ["7", "8"]
    if "7" in which:
        phase7()
    if "8" in which:
        phase8()
