"""Score the phase 6 fact-use test against its pre-registered predictions (RESULTS.md, "Phase 6 design").

Target items, per pipeline: the direct question is right and the two-hop question wrong in that
pipeline's own memory-off run. Writes runs/gemma3-4b-twohop/analysis.md.

  python analyze_phase6.py
"""

import os

import pandas as pd

from grader import grade

R = os.path.join("runs", "gemma3-4b-twohop")
W = os.path.join("runs", "gemma3-4b-twohop-edit")
P4 = os.path.join("runs", "gemma3-4b-phase4")


def load(path):
    return pd.read_csv(path).drop_duplicates("question").set_index("question")


def ids(x):
    return [int(i) for i in str(x).split(";") if i.strip() and i != "nan"]


def main():
    items = pd.read_csv("questions_twohop.csv")
    direct = pd.read_csv("questions_twohop_direct.csv")
    items["direct_question"] = direct["question"].values  # same row order (build_twohop.py)
    corr = pd.read_csv(os.path.join(P4, "corrections.csv"))
    own_id = dict(zip(corr["question"], corr["id"]))
    lines = ["# Phase 6 fact-use test — analysis (generated by analyze_phase6.py)", ""]

    def out(s=""):
        print(s)
        lines.append(s)

    def targets(d_off, t_off):
        return [r.question for r in items.itertuples()
                if d_off.loc[r.direct_question, "correct"] == 1 and t_off.loc[r.question, "correct"] == 0]

    def rate(run, qs):
        k = int(sum(run.loc[q, "correct"] for q in qs))
        return k, len(qs), k / max(len(qs), 1)

    # Retrieval pipeline
    r = {c: load(os.path.join(R, f"twohop_{c}.csv")) for c in ("off", "corrections", "gated", "oracle")}
    r_direct = load(os.path.join(R, "direct_off.csv"))
    tr = targets(r_direct, r["off"])
    # Weights pipeline
    w = {a: load(os.path.join(W, f"twohop_{a}.csv")) for a in ("off", "edited", "placebo")}
    w_direct = {a: load(os.path.join(W, f"direct_{a}.csv")) for a in ("off", "edited", "placebo")}
    tw = targets(w_direct["off"], w["off"])

    out(f"Items: {len(items)}. Target items (direct right, two-hop wrong, memory off): retrieval pipeline "
        f"{len(tr)}, weights pipeline {len(tw)}.")
    out()
    out("| pipeline | arm | two-hop acc (all items) | target items fixed |")
    out("|---|---|---|---|")
    for c in ("off", "corrections", "gated", "oracle"):
        k, n, f = rate(r[c], tr)
        out(f"| retrieval | {c} | {r[c]['correct'].mean():.1%} | {'—' if c == 'off' else f'{k} / {n} ({f:.1%})'} |")
    for a in ("off", "edited", "placebo"):
        k, n, f = rate(w[a], tw)
        out(f"| weights | {a} | {w[a]['correct'].mean():.1%} | {'—' if a == 'off' else f'{k} / {n} ({f:.1%})'} |")
    out()

    # P1 solvability
    out(f"**P1 (direct >= 50% right, memory off):** retrieval pipeline {r_direct['correct'].mean():.1%}, "
        f"weights pipeline {w_direct['off']['correct'].mean():.1%}.")
    for a in ("edited", "placebo"):
        out(f"  Direct questions under the {a} weights: {w_direct[a]['correct'].mean():.1%}.")

    # P2 gate finds the fact: own correction is top-1 and the gate (top-1 cos >= 0.7) fired
    own_top1 = [ids(r["corrections"].loc[x.question, "retrieved_correction_ids"])[:1] == [own_id[x.source_question]]
                for x in items.itertuples()]
    fired = [bool(ids(r["gated"].loc[x.question, "retrieved_correction_ids"])) for x in items.itertuples()]
    both = sum(a and b for a, b in zip(own_top1, fired))
    out(f"**P2 (own correction top-1 with cos >= 0.7 on >= 50%):** {both} / {len(items)} ({both / len(items):.1%}). "
        f"Own correction top-1 at any similarity: {sum(own_top1)}; gate fired at all: {sum(fired)}.")

    # P3 / P4
    ko, n, fo = rate(r["oracle"], tr)
    kg, _, fg = rate(r["gated"], tr)
    out(f"**P3 (oracle fixes >= 40% of targets):** {ko} / {n} ({fo:.1%}).")
    out(f"**P4 (oracle/2 <= gated <= oracle):** gated {kg}, oracle {ko}.")

    # P5 weights
    ke, nw, fe = rate(w["edited"], tw)
    kp, _, fp = rate(w["placebo"], tw)
    out(f"**P5 (edit fixes <= 10% of targets and <= placebo + 5 points):** edited {ke} / {nw} ({fe:.1%}), "
        f"placebo {kp} / {nw} ({fp:.1%}).")

    # P6 copying: still-wrong target items answered with the bridge entity
    bridge = dict(zip(items["question"], items["bridge_aliases"]))
    out("**P6 (>= 20% of still-wrong retrieval targets answered with the bridge entity):**")
    for c in ("corrections", "gated", "oracle"):
        wrong = [q for q in tr if r[c].loc[q, "correct"] == 0]
        cp = sum(grade(q, str(r[c].loc[q, "answer"]), bridge[q])[0] for q in wrong)
        base = sum(grade(q, str(r["off"].loc[q, "answer"]), bridge[q])[0] for q in wrong)
        out(f"  {c}: {cp} / {len(wrong)} ({cp / max(len(wrong), 1):.1%}); same items memory off: {base}.")
    wrong = [q for q in tw if w["edited"].loc[q, "correct"] == 0]
    cp = sum(grade(q, str(w["edited"].loc[q, "answer"]), bridge[q])[0] for q in wrong)
    out(f"  weights edited (not part of P6): {cp} / {len(wrong)}.")

    # Does the edit at least carry the bridge entity? Two-hop answers that mention it, any correctness.
    for a in ("off", "edited", "placebo"):
        m = sum(grade(q, str(w[a].loc[q, "answer"]), bridge[q])[0] for q in items["question"])
        out(f"  two-hop answers mentioning the bridge entity, weights {a}: {m} / {len(items)}")
    with open(os.path.join(R, "analysis.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
